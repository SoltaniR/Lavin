// Replay with: playwright-cli -s=lavin run-code --filename=tests/browser-smoke.js
// Uses synthetic records only and creates its own business workspace.
async (page) => {
  const base = new URL(page.url()).origin;
  const check = (condition, message) => { if (!condition) throw new Error(message); };
  await page.goto(base + '/?view=business&new=1');
  await page.getByRole('button', {name:'EN',exact:true}).click();
  await page.getByLabel('Business name').fill('QA Studio ' + Date.now());
  await page.getByLabel('VAT accounting method').selectOption('invoice');
  await page.getByLabel('This is my first financial year').check();
  await page.getByRole('button',{name:'Create workspace'}).click();
  await page.getByText('Saved successfully.',{exact:false}).waitFor();
  await page.goto(base + '/?view=review');
  async function entry(kind, description, amount, vat, debit, credit) {
    const panel = page.locator('.entry-panel');
    if (!(await panel.getAttribute('open') !== null)) await panel.locator('summary').click();
    await page.getByLabel('Entry type').selectOption(kind);
    await page.getByLabel('Description',{exact:true}).fill(description);
    await page.getByLabel('Total amount, including VAT').fill(amount);
    if (vat !== null) await page.getByLabel('VAT amount shown').fill(vat);
    if (debit) await page.getByRole('combobox',{name:'Debit',exact:true}).selectOption(debit);
    if (credit) await page.getByRole('combobox',{name:'Credit',exact:true}).selectOption(credit);
    await page.getByRole('button',{name:'Record entry',exact:true}).click();
    await panel.getByText('Saved successfully.',{exact:true}).waitFor();
  }
  await entry('opening','Synthetic opening capital','5410',null,'bank','capital');
  await page.reload();
  await entry('sale','Synthetic invoice INV-001','121','21');
  await page.goto(base + '/?view=documents');
  await page.locator('input[type=file]').setInputFiles('tests/fixtures/sample-bank.mt940');
  await page.getByRole('button',{name:'Upload and read'}).click();
  await page.getByText('sample-bank.mt940',{exact:true}).waitFor();
  await page.locator('input[type=file]').setInputFiles('tests/fixtures/sample-bank.mt940');
  await page.getByRole('button',{name:'Upload and read'}).click();
  await page.getByRole('alert').filter({hasText:'already'}).waitFor();
  const fixture = await page.context().newPage();
  await fixture.setContent('<h1>FACTUUR / INVOICE - SYNTHETIC TEST</h1><p>Studio Voorbeeld, Amsterdam</p><p>INV-001 | 5 maart 2025</p><p>Diensten / services: EUR 100.00</p><p>BTW / VAT 21%: EUR 21.00</p><p>Totaal / total: EUR 121.00</p><p>This is fictional test data, not a real invoice.</p>');
  await fixture.pdf({path:'output/playwright/synthetic-invoice.pdf',format:'A4'});
  await fixture.close();
  await page.locator('input[type=file]').setInputFiles('output/playwright/synthetic-invoice.pdf');
  await page.getByRole('button',{name:'Upload and read'}).click();
  await page.getByText('synthetic-invoice.pdf',{exact:true}).waitFor();
  const doc = page.locator('details.document').filter({hasText:'synthetic-invoice.pdf'});
  await doc.locator('summary').click();
  check((await doc.locator('pre').innerText()).includes('121.00'),'PDF text did not extract');
  const documentUrl = await doc.getByRole('link',{name:'View original'}).getAttribute('href');
  check((await page.request.get(base + documentUrl)).status() === 200,'Original document unavailable');
  await page.goto(base + '/?view=review');
  const first = page.locator('.bank-row').first();
  await first.getByRole('button',{name:'Record payment'}).click();
  await first.getByText('Recorded',{exact:true}).waitFor();
  const fee = page.locator('.bank-row').nth(1);
  await fee.getByRole('combobox').selectOption('otherCosts');
  await fee.getByRole('button',{name:'Record payment'}).click();
  await fee.getByText('Recorded',{exact:true}).waitFor();
  await page.goto(base + '/?view=yearend');
  const item = page.locator('details.requirement').first();
  await item.locator('summary').click();
  await item.getByRole('textbox').fill('Synthetic opening bank balance EUR 5,410.00, supported by test statement.');
  await item.getByRole('button',{name:'Save supporting note'}).click();
  await item.getByText('Notes supplied',{exact:true}).waitFor();
  await page.goto(base + '/?view=report&reportLocale=en');
  const paper = page.locator('.report-paper');
  check((await paper.innerText()).includes('89.00'),'Report profit does not reconcile');
  check((await paper.innerText()).includes('5,520.00'),'Report assets do not reconcile');
  await page.emulateMedia({media:'print'});
  await page.evaluate(() => document.fonts.ready);
  await page.pdf({path:'output/playwright/report-en.pdf',format:'A4',printBackground:true});
  const csv = await page.request.get(base + '/api/export');
  check(csv.status()===200 && (await csv.text()).includes('INV-001'),'Journal CSV failed');
  await page.emulateMedia({media:'screen'});
  await page.getByRole('button',{name:'NL',exact:true}).click();
  await page.getByRole('heading',{name:'Jaarrapport',exact:true}).waitFor();
  await page.goto(base + '/?view=report&reportLocale=nl');
  check((await paper.innerText()).includes('89,00'),'Dutch figures changed');
  await page.emulateMedia({media:'print'});
  await page.evaluate(() => document.fonts.ready);
  await page.pdf({path:'output/playwright/report-nl.pdf',format:'A4',printBackground:true});
  await page.emulateMedia({media:'screen'});
  await page.setViewportSize({width:390,height:844});
  await page.goto(base);
  check(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth),'Mobile page overflows horizontally');
  await page.screenshot({path:'output/playwright/mobile.png',fullPage:true});
  await page.setViewportSize({width:1440,height:1000});
  await page.getByRole('button',{name:'EN',exact:true}).click();
  await page.screenshot({path:'output/playwright/workspace.png',fullPage:true});
  console.log('PASS: business setup, manual journals, MT940 import, duplicate rejection, PDF extraction, bank posting, evidence, EN/NL reports, CSV, mobile layout.');
}
